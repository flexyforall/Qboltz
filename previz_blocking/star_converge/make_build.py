"""Regenerates build_star_converge.py: ONE self-contained file to run in Blender
(Scripting tab -> Open -> Run Script). Embeds previz_core, the solved bake and
the ray animation, so nothing has to sit at a particular path."""
import json, os
H = os.path.dirname(os.path.abspath(__file__))
def rnd(o):
    if isinstance(o, float): return round(o, 4)
    if isinstance(o, list): return [rnd(x) for x in o]
    if isinstance(o, tuple): return [rnd(x) for x in o]
    if isinstance(o, dict): return {k: rnd(v) for k, v in o.items()}
    return o
core = open(os.path.join(H, "previz_core.py")).read()
bake = json.dumps(rnd(json.load(open(os.path.join(H, "bake.json")))), separators=(",", ":"))
_R = json.load(open(os.path.join(H, "rays.json")))
for _m in _R.get("motes", []):
    # keep only the frames where the mote is lit, plus the dark frame either side
    g = _m.pop("glow"); n = len(g)
    _m["gk"] = [[f, g[f]] for f in range(n)
                if g[f] > 0 or (f and g[f - 1] > 0) or (f + 1 < n and g[f + 1] > 0)]
rays = json.dumps(rnd(_R), separators=(",", ":"))
out = '''"""star_converge -- blocking build. Run in Blender: Scripting tab -> Open this
file -> Run Script. Rebuilds the whole pass each time; touches nothing else.
Generated by make_build.py -- edit star_converge.py and re-solve, not this file."""
import bpy, json, math, os, tempfile

CORE = %r
BAKE = %r
RAYS = %r

# -- push the core once per session (re-pushed every run so edits always land)
mod = type(bpy)("PV"); mod.__dict__["__file__"] = "previz_core.py"
exec(CORE, mod.__dict__)
bpy.app.driver_namespace["PV"] = PV = mod

bake_path = os.path.join(tempfile.gettempdir(), "star_converge_bake.json")
open(bake_path, "w").write(BAKE)
R = json.loads(RAYS)

PV.wipe()
PV.reset(fps=R["fps"], seconds=R["frames"] / R["fps"])
# deep space: no floor, no sun, just a field of motes. The LOOK stays plain
# greybox (studio-lit solid, Blender's default grey world and AgX) so it reads
# as a blocking pass, not a styled render.
bpy.context.scene.world.color = (0.050876, 0.050876, 0.050876)
bpy.context.scene.view_settings.view_transform = 'AgX'

# no hub object: the rays leave from one bare point in the air -- a block there
# would hand the video model an object nobody wants in the shot
hx, hy, hz = R["hub"]

# six rays: long thin emissive slabs pivoting on the hub, base on the pivot,
# local +Z aimed at (az, el) -> euler XYZ = (pi/2 - el, 0, az + pi/2)
for r in R["rays"]:
    if r.get("cone"):
        # a soft cone of light: tiny at the source, opening to a fixed far width.
        # Translucent so it reads as scattered light, not a solid object.
        nm = "SET_ray_" + r["name"]
        old = bpy.data.objects.get(nm)
        if old: bpy.data.objects.remove(old, do_unlink=True)
        hw0, hw1, L = 0.03, r["cone"], r.get("length", R["length"])
        me_r = bpy.data.meshes.new(nm + "_m")
        me_r.from_pydata([(-hw0, -hw0, 0), (hw0, -hw0, 0), (hw0, hw0, 0), (-hw0, hw0, 0),
                          (-hw1, -hw1, L), (hw1, -hw1, L), (hw1, hw1, L), (-hw1, hw1, L)], [],
                         [(0, 3, 2, 1), (4, 5, 6, 7), (0, 1, 5, 4), (1, 2, 6, 5), (2, 3, 7, 6), (3, 0, 4, 7)])
        me_r.update()
        o = bpy.data.objects.new(nm, me_r); PV.coll("SET").objects.link(o)
        o.location = (hx, hy, hz)
        o.data.materials.append(PV._matfor(r["color"], emit=6.0))
    elif r.get("taper"):
        # a thin pyramid: square base on the source, apex at the far end -- the ray
        # narrows to nothing instead of stopping on a cut face
        nm = "SET_ray_" + r["name"]
        old = bpy.data.objects.get(nm)
        if old: bpy.data.objects.remove(old, do_unlink=True)
        hw, L = r.get("width", 0.10) / 2, r.get("length", R["length"])
        me_r = bpy.data.meshes.new(nm + "_m")
        me_r.from_pydata([(-hw, -hw, 0), (hw, -hw, 0), (hw, hw, 0), (-hw, hw, 0), (0, 0, L)], [],
                         [(0, 3, 2, 1), (0, 1, 4), (1, 2, 4), (2, 3, 4), (3, 0, 4)])
        me_r.update()
        o = bpy.data.objects.new(nm, me_r); PV.coll("SET").objects.link(o)
        o.location = (hx, hy, hz)
        o.data.materials.append(PV._matfor(r["color"], emit=6.0))
    else:
        o = PV.slab("SET_ray_" + r["name"], (r.get("width", 0.10), r.get("width", 0.10),
                    r.get("length", R["length"])), (hx, hy, hz),
                    r["color"], emit=6.0, base=True)
    o.color = (*PV.PALETTE[r["color"]], 0.3 if r.get("cone") else 1.0)
    o.rotation_mode = 'XYZ'
    ch = {("rotation_euler", 0): [math.pi / 2 - e for e in r["el"]],
          ("rotation_euler", 1): [0.0] * len(r["el"]),
          ("rotation_euler", 2): [a + math.pi / 2 for a in r["az"]]}
    if "len" in r:                           # rays reach SCAN length, then stretch far away
        ch[("scale", 2)] = [L / r.get("length", R["length"]) for L in r["len"]]
    if "alpha" in r:                         # the wide cone dims as the star takes over
        c0 = PV.PALETTE[r["color"]]
        for k in range(3): ch[("color", k)] = [c0[k]] * len(r["alpha"])
        ch[("color", 3)] = r["alpha"]
    if "merged_at" in r:                     # folded into the hero: gone, one ray remains
        sx = [1.0 if f < r["merged_at"] else 0.001 for f in range(len(r["el"]))]
        ch[("scale", 0)] = sx; ch[("scale", 1)] = sx
    PV.bake(o, ch)

# light pulse running out along one ray: a short white sleeve around the beam,
# scaled to nothing whenever it is not running (d < 0)
P = R.get("pulse")
if P:
    c = next(r for r in R["rays"] if r["name"] == P["ray"])
    o = PV.slab("SET_pulse", (0.26, 0.26, 3.0), (hx, hy, hz), "white", emit=12.0, base=True)
    o.color = (1.0, 1.0, 1.0, 1.0)
    o.rotation_mode = 'XYZ'
    L = {k: [] for k in range(3)}; S = []
    for d, az, el in zip(P["d"], c["az"], c["el"]):
        dd = max(d, 0.0)
        v = (math.cos(el) * math.cos(az), math.cos(el) * math.sin(az), math.sin(el))
        for k, h0 in enumerate((hx, hy, hz)): L[k].append(h0 + v[k] * dd)
        S.append(1.0 if d >= 0 else 0.001)
    ch = {("location", k): L[k] for k in range(3)}
    ch.update({("rotation_euler", 0): [math.pi / 2 - e for e in c["el"]],
               ("rotation_euler", 1): [0.0] * len(S),
               ("rotation_euler", 2): [a + math.pi / 2 for a in c["az"]]})
    ch.update({("scale", k): S for k in range(3)})
    PV.bake(o, ch)

# the target: what the beam was looking for. A magenta sphere riding ray C at a
# fixed distance, scaled from nothing (0.001) to its full size.
T = R.get("target")
if T:
    c = next(r for r in R["rays"] if r["name"] == T["ray"])
    me_t = bpy.data.meshes.get("TARGET_sphere")
    if me_t is None:
        import bmesh as _bm
        me_t = bpy.data.meshes.new("TARGET_sphere"); b = _bm.new()
        _bm.ops.create_uvsphere(b, u_segments=32, v_segments=16, radius=1.0)
        b.to_mesh(me_t); b.free()
        for p in me_t.polygons: p.use_smooth = True
    o = bpy.data.objects.new("SET_target", me_t); PV.coll("SET").objects.link(o)
    o.data.materials.clear(); o.data.materials.append(PV._matfor("magenta", emit=6.0))
    o.color = (*PV.PALETTE["magenta"], 1.0)
    L = {k: [] for k in range(3)}; S = []
    for rr, az, el in zip(T["r"], c["az"], c["el"]):
        v = (math.cos(el) * math.cos(az), math.cos(el) * math.sin(az), math.sin(el))
        for k, h0 in enumerate((hx, hy, hz)): L[k].append(h0 + v[k] * T["dist"])
        S.append(max(rr, 0.001))
    ch = {("location", k): L[k] for k in range(3)}
    ch.update({("scale", k): S for k in range(3)})
    PV.bake(o, ch)

# motes: small round points drifting slowly in space. Dim grey-white at rest,
# ORANGE while a beam passes through them -- that flash is the scan.
import bmesh
me = bpy.data.meshes.get("MOTE_sphere")
if me is None:
    me = bpy.data.meshes.new("MOTE_sphere"); bm = bmesh.new()
    bmesh.ops.create_uvsphere(bm, u_segments=10, v_segments=6, radius=1.0)
    bm.to_mesh(me); bm.free()
BASE, LIT = (0.42, 0.42, 0.46), (1.0, 0.38, 0.0)
NF = R["frames"]
mc = PV.coll("SET")
for i, mo in enumerate(R.get("motes", [])):
    o = bpy.data.objects.new("SET_mote_%%03d" %% i, me); mc.objects.link(o)
    o.scale = (mo["r"],) * 3
    o.color = (*BASE, 1.0)
    cb = PV._cbag(o, "ACT_mote_%%03d" %% i, 'OBJECT', o.name)
    if R.get("mote_motion") == "rings":      # orbit on a tilted ring round the source
        p0, ax, w = mo["p0"], mo["axis"], mo["w"]
        fr = list(range(1, NF + 1, 4)) + ([NF] if (NF - 1) %% 4 else [])
        co = {0: [], 1: [], 2: []}
        for f in fr:
            a_ = w * (f - 1) / R["fps"]; c, s_ = math.cos(a_), math.sin(a_)
            kxp = (ax[1]*p0[2]-ax[2]*p0[1], ax[2]*p0[0]-ax[0]*p0[2], ax[0]*p0[1]-ax[1]*p0[0])
            kp = ax[0]*p0[0] + ax[1]*p0[1] + ax[2]*p0[2]
            for k, h0 in enumerate((hx, hy, hz)):
                co[k] += [f, h0 + p0[k]*c + kxp[k]*s_ + ax[k]*kp*(1-c)]
        for k in range(3):
            fc = cb.fcurves.new("location", index=k)
            fc.keyframe_points.add(len(fr))
            fc.keyframe_points.foreach_set("co", co[k])
            fc.keyframe_points.foreach_set("interpolation", [1] * len(fr)); fc.update()
    elif R.get("mote_motion") == "swirl":    # swirl round the source + slow outward drift
        p0, w, vr, r0 = mo["p0"], mo["w"], mo["vr"], mo["r0"]
        fr = list(range(1, NF + 1, 4)) + ([NF] if (NF - 1) %% 4 else [])
        co = {0: [], 1: [], 2: []}
        for f in fr:
            t = (f - 1) / R["fps"]; c, s_ = math.cos(w * t), math.sin(w * t)
            k_ = 1.0 + vr * t / max(r0, 1e-6)
            pos = (hx + k_ * (c * p0[0] - s_ * p0[1]), hy + k_ * (s_ * p0[0] + c * p0[1]), hz + k_ * p0[2])
            for k in range(3): co[k] += [f, pos[k]]
        for k in range(3):
            fc = cb.fcurves.new("location", index=k)
            fc.keyframe_points.add(len(fr))
            fc.keyframe_points.foreach_set("co", co[k])
            fc.keyframe_points.foreach_set("interpolation", [1] * len(fr)); fc.update()
    else:
        p0, v = mo["p0"], mo["v"]
        for k in range(3):                   # straight constant drift: 2 linear keys
            fc = cb.fcurves.new("location", index=k)
            fc.keyframe_points.add(2)
            fc.keyframe_points.foreach_set("co", [1, p0[k], NF, p0[k] + v[k] * (NF - 1) / R["fps"]])
            fc.keyframe_points.foreach_set("interpolation", [1, 1]); fc.update()
    gk = mo["gk"]
    if gk:
        for k in range(3):
            fc = cb.fcurves.new("color", index=k)
            fc.keyframe_points.add(len(gk))
            fc.keyframe_points.foreach_set("co", [x for f, g in gk for x in (f + 1, BASE[k] + (LIT[k] - BASE[k]) * g)])
            fc.keyframe_points.foreach_set("interpolation", [1] * len(gk)); fc.update()

# the source's glow: a white sphere marker that blooms into the star at the end
C_ = R.get("core")
if C_:
    me_c = bpy.data.meshes.get("CORE_sphere")
    if me_c is None:
        import bmesh as _bm
        me_c = bpy.data.meshes.new("CORE_sphere"); b = _bm.new()
        _bm.ops.create_uvsphere(b, u_segments=24, v_segments=12, radius=1.0)
        b.to_mesh(me_c); b.free()
        for p in me_c.polygons: p.use_smooth = True
    o = bpy.data.objects.new("SET_core", me_c); PV.coll("SET").objects.link(o)
    o.location = (hx, hy, hz)
    o.data.materials.clear(); o.data.materials.append(PV._matfor("white", emit=8.0))
    o.color = (1.0, 1.0, 1.0, 1.0)
    PV.bake(o, {("scale", k): C_["r"] for k in range(3)})

# the solver's subject is the camera's ATTENTION target -- bake it, audit
# against it, then hide it: it is a rig part, not something in the shot
PV.actor("HERO", size=(1.0, 1.0, 1.0), color="magenta")
PV.load_bake(bake_path)
print("AUDIT", PV.audit())
blk = bpy.data.objects["HERO_block"]
blk.hide_render = True
blk.hide_set(True)

print(PV.viewport_ready())
ds = bpy.context.scene.display.shading                # what PV.motion_render() uses
ds.light, ds.color_type = 'STUDIO', 'OBJECT'

# fill every 3D view with the camera frame (View -> Frame Camera Bounds)
for w in bpy.context.window_manager.windows:
    for a in w.screen.areas:
        if a.type != 'VIEW_3D': continue
        a.spaces.active.show_gizmo = True     # keep the camera / zoom / pan buttons on the right
        sh = a.spaces.active.shading
        # studio-lit solid like every earlier pass; OBJECT colour only so a
        # mote can flash orange on its own (rays carry their palette colour)
        sh.light, sh.color_type, sh.background_type = 'STUDIO', 'OBJECT', 'THEME'
        rg = next((r for r in a.regions if r.type == 'WINDOW'), None)
        try:
            with bpy.context.temp_override(window=w, screen=w.screen, area=a, region=rg):
                bpy.ops.view3d.view_center_camera()
        except Exception as e:
            print("frame camera bounds skipped:", e)
''' % (core, bake, rays)
open(os.path.join(H, "build_star_converge.py"), "w").write(out)
