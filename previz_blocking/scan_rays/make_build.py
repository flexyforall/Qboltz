"""Regenerates build_scan_rays.py: ONE self-contained file to run in Blender
(Scripting tab -> Open -> Run Script). Embeds previz_core, the solved bake and
the ray animation, so nothing has to sit at a particular path."""
import json, os
H = os.path.dirname(os.path.abspath(__file__))
def rnd(o):
    if isinstance(o, float): return round(o, 4)
    if isinstance(o, list): return [rnd(x) for x in o]
    if isinstance(o, tuple): return [rnd(x) for x in o]
    if isinstance(o, dict): return {k: rnd(v) for k, v in o.items()}
    return o
core = open(os.path.join(H, "previz_core.py")).read()
bake = json.dumps(rnd(json.load(open(os.path.join(H, "bake.json")))), separators=(",", ":"))
rays = json.dumps(rnd(json.load(open(os.path.join(H, "rays.json")))), separators=(",", ":"))
out = '''"""scan_rays -- blocking build. Run in Blender: Scripting tab -> Open this
file -> Run Script. Rebuilds the whole pass each time; touches nothing else.
Generated by make_build.py -- edit scan_rays.py and re-solve, not this file."""
import bpy, json, math, os, tempfile

CORE = %r
BAKE = %r
RAYS = %r

# -- push the core once per session (re-pushed every run so edits always land)
mod = type(bpy)("PV"); mod.__dict__["__file__"] = "previz_core.py"
exec(CORE, mod.__dict__)
bpy.app.driver_namespace["PV"] = PV = mod

bake_path = os.path.join(tempfile.gettempdir(), "scan_rays_bake.json")
open(bake_path, "w").write(BAKE)
R = json.loads(RAYS)

PV.wipe()
PV.reset(fps=R["fps"], seconds=R["frames"] / R["fps"])
PV.checker()                                   # no place named -> the void
PV.sun()

# the hub: one bright block the six rays leave from
hx, hy, hz = R["hub"]
PV.slab("SET_hub", (0.6, 0.6, 0.6), (hx, hy, hz), "white", emit=4.0)

# six rays: long thin emissive slabs pivoting on the hub, base on the pivot,
# local +Z aimed at (az, el) -> euler XYZ = (pi/2 - el, 0, az + pi/2)
for r in R["rays"]:
    o = PV.slab("SET_ray_" + r["name"], (r.get("width", 0.10), r.get("width", 0.10),
                r.get("length", R["length"])), (hx, hy, hz),
                r["color"], emit=6.0, base=True)
    o.rotation_mode = 'XYZ'
    PV.bake(o, {("rotation_euler", 0): [math.pi / 2 - e for e in r["el"]],
                ("rotation_euler", 1): [0.0] * len(r["el"]),
                ("rotation_euler", 2): [a + math.pi / 2 for a in r["az"]]})

# light pulse running out along one ray: a short white sleeve around the beam,
# scaled to nothing whenever it is not running (d < 0)
P = R.get("pulse")
if P:
    c = next(r for r in R["rays"] if r["name"] == P["ray"])
    o = PV.slab("SET_pulse", (0.26, 0.26, 3.0), (hx, hy, hz), "white", emit=12.0, base=True)
    o.rotation_mode = 'XYZ'
    L = {k: [] for k in range(3)}; S = []
    for d, az, el in zip(P["d"], c["az"], c["el"]):
        dd = max(d, 0.0)
        v = (math.cos(el) * math.cos(az), math.cos(el) * math.sin(az), math.sin(el))
        for k, h0 in enumerate((hx, hy, hz)): L[k].append(h0 + v[k] * dd)
        S.append(1.0 if d >= 0 else 0.001)
    ch = {("location", k): L[k] for k in range(3)}
    ch.update({("rotation_euler", 0): [math.pi / 2 - e for e in c["el"]],
               ("rotation_euler", 1): [0.0] * len(S),
               ("rotation_euler", 2): [a + math.pi / 2 for a in c["az"]]})
    ch.update({("scale", k): S for k in range(3)})
    PV.bake(o, ch)

# the solver's subject is the camera's ATTENTION target -- bake it, audit
# against it, then hide it: it is a rig part, not something in the shot
PV.actor("HERO", size=(1.0, 1.0, 1.0), color="magenta")
PV.load_bake(bake_path)
print("AUDIT", PV.audit())
blk = bpy.data.objects["HERO_block"]
blk.hide_render = True
blk.hide_set(True)

print(PV.viewport_ready())

# fill every 3D view with the camera frame (View -> Frame Camera Bounds)
for w in bpy.context.window_manager.windows:
    for a in w.screen.areas:
        if a.type != 'VIEW_3D': continue
        a.spaces.active.show_gizmo = True     # keep the camera / zoom / pan buttons on the right
        rg = next((r for r in a.regions if r.type == 'WINDOW'), None)
        try:
            with bpy.context.temp_override(window=w, screen=w.screen, area=a, region=rg):
                bpy.ops.view3d.view_center_camera()
        except Exception as e:
            print("frame camera bounds skipped:", e)
''' % (core, bake, rays)
open(os.path.join(H, "build_scan_rays.py"), "w").write(out)
# live.py is what live_link.py in Blender watches: the current pass, always
open(os.path.join(os.path.dirname(H), "live.py"), "w").write(out)
print("build ->", os.path.join(H, "build_scan_rays.py"), "%.0f KB" % (len(out) / 1024))
